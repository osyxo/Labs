if __name__ == "__main__":
    print("--- Лабораторна робота №9 ---")
    
    # -------------------------------------------------------------------------
    # ХІД РОБОТИ. ПУНКТ 3: Тестування програми на функції Розенброка
    # -------------------------------------------------------------------------
    print("\n[Пункт 3] Тестування алгоритму на функції Розенброка:")
    rosen_x0 = [-1.2, 0.0]  # Початкова точка з методички
    rosen_delta = [0.1, 0.1]
    eps1, eps2 = 1e-5, 1e-5
    
    res_rosen, traj_rosen = hooke_jeeves(rosenbrock, rosen_x0, rosen_delta, eps1, eps2)
    print(f"  Знайдений мінімум: {res_rosen}")
    print(f"  Значення функції:  {rosenbrock(res_rosen):.2e}")
    print(f"  Кількість кроків траєкторії: {len(traj_rosen)}")

    # -------------------------------------------------------------------------
    # ХІД РОБОТИ. ПУНКТ 4: Знаходження розв'язку заданої системи рівнянь
    # -------------------------------------------------------------------------
    print("\n[Пункт 4] Розв'язання системи нелінійних рівнянь:")
    # Параметри пошуку для нашої системи
    sys_x0 = [1.0, 2.0]        # Початкове наближення (базисна точка)
    sys_delta = [0.2, 0.2]     # Початковий крок
    sys_eps1 = 1e-6            # Критерій закінчення по кроку
    sys_eps2 = 1e-6            # Критерій закінчення по функції
    
    res_sys, traj_sys = hooke_jeeves(target_function, sys_x0, sys_delta, sys_eps1, sys_eps2)
    print(f"  Знайдений розв'язок системи X*: {res_sys}")
    print(f"  Значення цільової функції Ф(X*): {target_function(res_sys):.2e}")
    print(f"  Перевірка рівнянь: f1(X*) = {f1(res_sys):.4f}, f2(X*) = {f2(res_sys):.4f}")

    # -------------------------------------------------------------------------
    # ХІД РОБОТИ. ПУНКТ 5: Запис траєкторії спуску у файл
    # -------------------------------------------------------------------------
    filename = "trajectory.txt"
    with open(filename, "w") as f_out:
        f_out.write("Крок\tX1\t\tX2\t\tФ(X)\n")
        f_out.write("-" * 45 + "\n")
        for idx, pt in enumerate(traj_sys):
            f_out.write(f"{idx}\t{pt[0]:.6f}\t{pt[1]:.6f}\t{target_function(pt):.2e}\n")
            
    print(f"\n[Пункт 5] Координати траєкторії спуску записано у файл '{filename}'.")
    print(f"  Загальна кількість кроків на траєкторії спуску: {len(traj_sys) - 1}")

    # -------------------------------------------------------------------------
    # ХІД РОБОТИ. ПУНКТ 1 (Графічна частина): Візуалізація рівнянь та спуску
    # -------------------------------------------------------------------------
    # Створення сітки для графіків
    x1_vals = np.linspace(-3, 3, 400)
    x2_vals = np.linspace(-3, 3, 400)
    X1, X2 = np.meshgrid(x1_vals, x2_vals)
    
    plt.figure(figsize=(8, 6))
    
    # Лінії рівня f1(x)=0 (коло) та f2(x)=0 (пряма)
    plt.contour(X1, X2, X1**2 + X2**2 - 4, levels=[0], colors='blue', linewidths=2, labels='f1(x)=0')
    plt.contour(X1, X2, X1 - X2 - 1, levels=[0], colors='green', linewidths=2, labels='f2(x)=0')
    
    # Відображення траєкторії алгоритму
    traj_sys = np.array(traj_sys)
    plt.plot(traj_sys[:, 0], traj_sys[:, 1], 'r.-', label='Траєкторія Хука-Дживса')
    plt.plot(sys_x0[0], sys_x0[1], 'go', label='Старт X(0)')
    plt.plot(res_sys[0], res_sys[1], 'ks', label='Знайдений корінь X*')
    
    plt.title("Візуалізація розв'язку системи рівнянь та траєкторія спуску")
    plt.xlabel("x1")
    plt.ylabel("x2")
    plt.grid(True)
    plt.legend()
    
    print("\n[Пункт 1] Графік побудовано. Закрийте вікно графіка для завершення програми.")
    plt.show()