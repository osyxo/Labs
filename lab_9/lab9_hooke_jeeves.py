import numpy as np
import matplotlib.pyplot as plt

# =============================================================================
# ХІД РОБОТИ. ПУНКТ 1: Задаємо систему нелінійних рівнянь (m=2)
# =============================================================================
# Нехай маємо систему:
# f1(x1, x2) = x1^2 + x2^2 - 4 = 0  (коло радіуса 2)
# f2(x1, x2) = x1 - x2 - 1 = 0      (пряма)
def f1(x):
    return x[0]**2 + x[1]**2 - 4

def f2(x):
    return x[0] - x[1] - 1

# Побудова цільової функції згідно з формулою: Ф(x) = sum(fi^2)
def target_function(x):
    """Допоміжна цільова функція для системи рівнянь"""
    return f1(x)**2 + f2(x)**2

# ПУНКТ 3 (Тестування): Функція Розенброка для перевірки алгоритму
def rosenbrock(x):
    """Тестова функція Розенброка"""
    return 100 * (x[0]**2 - x[1])**2 + (x[0] - 1)**2


# =============================================================================
# ХІД РОБОТИ. ПУНКТ 2: Програма знаходження мінімуму методом Хука-Дживса
# =============================================================================
def hooke_jeeves(func, x0, delta_x, eps1, eps2, q=2.0, p=2.0, max_iter=1000):
    """
    Реалізація алгоритму Хука-Дживса відповідно до розділу 'Основні відомості'.
    """
    # Список для збереження траєкторії спуску (Хід роботи, Пункт 5)
    trajectory = []
    
    # Пункт 1-2: Задаємо початкові параметри та наближення
    x0 = np.array(x0, dtype=float)
    delta = np.array(delta_x, dtype=float)
    n = len(x0)
    
    # Зберігаємо початкову точку в траєкторію
    trajectory.append(x0.copy())
    
    k = 0
    while k < max_iter:
        # --- ДОСЛІДЖУЮЧИЙ ПОШУК ---
        # Пункт 3: Задаємо початкове значення для дослідження
        x1 = x0.copy()
        
        # Пункт 4: Цикл по координатах
        for i in range(n):
            # Пробуємо крок у бік плюс
            x_try = x1.copy()
            x_try[i] += delta[i]
            
            if func(x_try) < func(x0):
                x1 = x_try
            else:
                # Пробуємо крок у бік мінус
                x_try = x1.copy()
                x_try[i] -= delta[i]
                if func(x_try) < func(x0):
                    x1 = x_try
                else:
                    # Зменшуємо величину кроку по змінній
                    delta[i] /= q
                    # Якщо крок став меншим за eps1, фіксуємо стару координату
                    if delta[i] < eps1:
                        x1[i] = x0[i]

        # Пункт 5: Перевірка умов закінчення або переходу до пошуку по зразку
        # Перевірка умови X(1) != X(0)
        if not np.array_equal(x1, x0):
            # Перевірка критеріїв закінчення пошуку
            norm_delta = np.linalg.norm(delta)
            func_diff = abs(func(x1) - func(x0))
            
            if norm_delta < eps1 and func_diff < eps2:
                trajectory.append(x1.copy())
                return x1, trajectory  # Точка мінімуму знайдена
                
            # Пункт 6-7: ПОШУК ПО ЗРАЗКУ
            # Знаходимо наступну точку Xp2 = X(1) + p*(X(1) - X(0))
            xp2 = x1 + p * (x1 - x0)
            
            # Пункт 8: Досліджуючий пошук з точки Xp2 (без зменшення кроку)
            x2 = xp2.copy()
            for i in range(n):
                x_try = x2.copy()
                x_try[i] += delta[i]
                if func(x_try) < func(xp2):
                    x2 = x_try
                else:
                    x_try = x2.copy()
                    x_try[i] -= delta[i]
                    if func(x_try) < func(xp2):
                        x2 = x_try
            
            # Пункт 9: Перевірка умов результату пошуку по зразку
            if func(x2) < func(x1):
                x0 = x1.copy()
                x1 = x2.copy()
                trajectory.append(x1.copy())
                # Повертаємось до пошуку по зразку (пункт 6)
                continue
            else:
                x0 = x1.copy()
                trajectory.append(x0.copy())
                # Повторюємо досліджуючий пошук (пункт 2)
                continue
        else:
            # Якщо X(1) == X(0), то поточна точка є мінімумом (або кроки замалі)
            if np.all(delta < eps1):
                return x0, trajectory
            else:
                # Якщо кроки ще великі, зменшуємо їх для відновлення дослідження
                delta /= q


